"""Merchant retention policy: the schema the plain-English compiler must produce, and a
code-generated summary the merchant approves (the LLM never writes the summary, so it can't misstate the rules)."""
from typing import Literal

from pydantic import BaseModel, Field, model_validator

Category = Literal["temporary", "price", "low_usage", "product_problem", "competitor", "other"]
ActionType = Literal["pause", "discount", "downgrade", "cancel"]

CATEGORIES: tuple[str, ...] = ("temporary", "price", "low_usage", "product_problem", "competitor", "other")
CATEGORY_LABELS = {
    "temporary": "temporary break (travel, exams, busy)", "price": "price / money",
    "low_usage": "not using it enough", "product_problem": "problem with the product",
    "competitor": "moving to a competitor", "other": "other",
}


class PolicyRules(BaseModel):
    pause_enabled: bool = True
    max_pause_months: int = Field(3, ge=1, le=6)
    min_paid_months_for_pause: int = Field(0, ge=0, le=24)
    discount_enabled: bool = True
    max_discount_pct: int = Field(30, ge=0, le=90)
    min_paid_months_for_discount: int = Field(2, ge=0, le=24)
    discount_only_for: list[Category] = Field(default_factory=list,
                                              description="If non-empty, discounts only for these reason categories")
    downgrade_enabled: bool = True
    max_offers_per_subscriber: int = Field(1, ge=0, le=5)
    no_offer_for: list[Category] = Field(default_factory=list,
                                         description="Reason categories that get no offer, just a clean cancel")
    prefer: dict[Category, ActionType] = Field(default_factory=dict,
                                               description="Soft preference per reason category")

    @model_validator(mode="after")
    def _no_conflicts(self) -> "PolicyRules":
        if not self.discount_enabled:
            self.discount_only_for = []
        for cat, act in list(self.prefer.items()):
            if act == "discount" and not self.discount_enabled or act == "pause" and not self.pause_enabled \
                    or act == "downgrade" and not self.downgrade_enabled:
                del self.prefer[cat]  # a preference for a disabled action can never apply
        return self


def summarize(rules: PolicyRules) -> list[str]:
    """Readable lines generated by code from the validated rules."""
    lines = []
    if rules.pause_enabled:
        cond = f" after {rules.min_paid_months_for_pause} paid months" if rules.min_paid_months_for_pause else ""
        lines.append(f"Pause: up to {rules.max_pause_months} month(s){cond}.")
    else:
        lines.append("Pause: never offered.")
    if rules.discount_enabled and rules.max_discount_pct > 0:
        cond = f" after {rules.min_paid_months_for_discount} paid months" if rules.min_paid_months_for_discount else ""
        who = (" only when the reason is " + ", ".join(CATEGORY_LABELS[c] for c in rules.discount_only_for)
               if rules.discount_only_for else "")
        lines.append(f"Discount: at most {rules.max_discount_pct}% off{cond}{who}.")
    else:
        lines.append("Discount: never offered.")
    lines.append("Cheaper plan: allowed." if rules.downgrade_enabled else "Cheaper plan: never offered.")
    lines.append(f"At most {rules.max_offers_per_subscriber} offer(s) per subscriber, ever."
                 if rules.max_offers_per_subscriber else "No offers at all: every cancel goes straight through.")
    if rules.no_offer_for:
        lines.append("No offer (clean cancel) when the reason is: "
                     + ", ".join(CATEGORY_LABELS[c] for c in rules.no_offer_for) + ".")
    for cat, act in rules.prefer.items():
        lines.append(f"Prefer {act} when the reason is {CATEGORY_LABELS[cat]}.")
    lines.append("Cancelling is always possible: the subscriber can always say no.")
    return lines


def diff(old: PolicyRules, new: PolicyRules) -> list[dict]:
    a, b = old.model_dump(), new.model_dump()
    return [{"field": k, "old": a[k], "new": b[k]} for k in a if a[k] != b[k]]


DEFAULT_RULES = PolicyRules(prefer={"temporary": "pause", "price": "discount", "low_usage": "downgrade"})
DEFAULT_SOURCE = ("Offer a pause of up to 3 months to anyone. Discounts are at most 30% and only after 2 paid "
                  "months. Cheaper plan is fine. One offer per customer. Pause for people who are travelling or "
                  "busy, discount for people worried about money, Lite for people not using it much.")
